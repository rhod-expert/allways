'use strict';

/**
 * Pre-launch backup: dumps PARTICIPANTES, REGISTROS, CUPONES,
 * and PREMIOS sorteo state to a restorable .sql file.
 *
 * Usage: node scripts/backup-pre-launch.js
 */

const fs = require('fs');
const path = require('path');

// Parse backend/.env without dotenv dependency
const envPath = path.resolve(__dirname, '..', 'backend', '.env');
for (const line of fs.readFileSync(envPath, 'utf8').split('\n')) {
  const m = line.match(/^([A-Z_][A-Z0-9_]*)=(.*)$/);
  if (m && !process.env[m[1]]) process.env[m[1]] = m[2];
}

const oracledb = require(path.resolve(__dirname, '..', 'backend', 'node_modules', 'oracledb'));

const BACKUP_DIR = path.resolve(__dirname, '..', 'backups', 'pre-launch-2026-04-30');
const SQL_FILE = path.join(BACKUP_DIR, 'backup.sql');
const COUNTS_FILE = path.join(BACKUP_DIR, 'counts-before.txt');

oracledb.initOracleClient({ configDir: '/usr/lib/oracle/19.25/client64/lib/network/admin' });
oracledb.outFormat = oracledb.OUT_FORMAT_OBJECT;

function quoteSqlValue(v) {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return String(v);
  if (v instanceof Date) {
    const iso = v.toISOString().replace('T', ' ').replace('Z', '').split('.')[0];
    return `TO_TIMESTAMP('${iso}', 'YYYY-MM-DD HH24:MI:SS')`;
  }
  const s = String(v).replace(/'/g, "''");
  return `'${s}'`;
}

function buildInsert(table, rows) {
  if (rows.length === 0) return `-- ${table}: 0 rows\n`;
  const cols = Object.keys(rows[0]);
  const lines = [`-- ${table}: ${rows.length} rows`];
  for (const r of rows) {
    const vals = cols.map((c) => quoteSqlValue(r[c])).join(', ');
    lines.push(`INSERT INTO ${table} (${cols.join(', ')}) VALUES (${vals});`);
  }
  lines.push('');
  return lines.join('\n');
}

(async () => {
  const conn = await oracledb.getConnection({
    user: process.env.ORACLE_USER,
    password: process.env.ORACLE_PASSWORD,
    connectString: process.env.ORACLE_CONNECTION_STRING
  });

  console.log('[BACKUP] Conectado. Contando filas...');

  const counts = (await conn.execute(`
    SELECT
      (SELECT COUNT(*) FROM ALLWAYS_PARTICIPANTES) AS PARTICIPANTES,
      (SELECT COUNT(*) FROM ALLWAYS_REGISTROS) AS REGISTROS,
      (SELECT COUNT(*) FROM ALLWAYS_CUPONES) AS CUPONES,
      (SELECT COUNT(*) FROM ALLWAYS_PREMIOS) AS PREMIOS_TOTAL,
      (SELECT COUNT(*) FROM ALLWAYS_PREMIOS WHERE CUPON_GANADOR_ID IS NOT NULL) AS PREMIOS_SORTEADOS,
      (SELECT COUNT(*) FROM ALLWAYS_ADMIN) AS ADMINS,
      (SELECT COUNT(*) FROM ALLWAYS_ADMIN_LOG) AS ADMIN_LOG
    FROM DUAL
  `)).rows[0];

  console.log('[BACKUP] Contagens:', counts);
  fs.writeFileSync(COUNTS_FILE, JSON.stringify(counts, null, 2) + '\n');

  // Dump tables (order matters for restore: PARTICIPANTES → REGISTROS → CUPONES)
  console.log('[BACKUP] Volcando ALLWAYS_PARTICIPANTES...');
  const parts = (await conn.execute(`
    SELECT ID, NOMBRE, CEDULA, TELEFONO, EMAIL, CIUDAD, DEPARTAMENTO,
           DEPARTAMENTO_ID, DISTRITO_ID, CIUDAD_ID, BARRIO_ID,
           CALLE, NUMERO_CASA, COMPLEMENTO,
           FECHA_REGISTRO, ACTIVO
    FROM ALLWAYS_PARTICIPANTES
    ORDER BY ID
  `)).rows;

  console.log('[BACKUP] Volcando ALLWAYS_REGISTROS...');
  const regs = (await conn.execute(`
    SELECT ID, PARTICIPANTE_ID, NUMERO_FACTURA, CANTIDAD_PRODUCTOS,
           IMAGEN_FACTURA, IMAGEN_PRODUCTOS, ESTADO,
           MOTIVO_RECHAZO, VALIDADO_POR, FECHA_VALIDACION,
           FECHA_REGISTRO, IP_REGISTRO
    FROM ALLWAYS_REGISTROS
    ORDER BY ID
  `)).rows;

  console.log('[BACKUP] Volcando ALLWAYS_CUPONES...');
  const cups = (await conn.execute(`
    SELECT ID, REGISTRO_ID, PARTICIPANTE_ID, NUMERO_CUPON,
           MES_SORTEO, GANADOR, FECHA_GENERACION
    FROM ALLWAYS_CUPONES
    ORDER BY ID
  `)).rows;

  console.log('[BACKUP] Volcando estado de ALLWAYS_PREMIOS...');
  const premiosState = (await conn.execute(`
    SELECT ID, MES, DESCRIPCION, CUPON_GANADOR_ID, FECHA_SORTEO
    FROM ALLWAYS_PREMIOS
    WHERE CUPON_GANADOR_ID IS NOT NULL OR FECHA_SORTEO IS NOT NULL
    ORDER BY ID
  `)).rows;

  await conn.close();

  // Build SQL file
  const header = `-- ============================================================
-- Allways pre-launch backup
-- Generated: ${new Date().toISOString()}
-- Counts: PARTICIPANTES=${counts.PARTICIPANTES}, REGISTROS=${counts.REGISTROS}, CUPONES=${counts.CUPONES}
-- Premios already sorteados (state to restore): ${premiosState.length}
--
-- RESTORE INSTRUCTIONS:
-- 1. Connect to Oracle as the ALLWAYS user
-- 2. Run the INSERTs below in order (PARTICIPANTES → REGISTROS → CUPONES)
-- 3. NOTE: ID columns are IDENTITY GENERATED ALWAYS — to restore exact IDs
--    you must temporarily ALTER each column to GENERATED BY DEFAULT.
--    Otherwise omit the ID column from the INSERT statements.
-- 4. After restore, run the UPDATE statements to restore PREMIOS sorteo state.
-- 5. COMMIT.
-- ============================================================

SET DEFINE OFF;

`;

  let body = '';
  body += buildInsert('ALLWAYS_PARTICIPANTES', parts) + '\n';
  body += buildInsert('ALLWAYS_REGISTROS', regs) + '\n';
  body += buildInsert('ALLWAYS_CUPONES', cups) + '\n';

  // Premios state restore (UPDATEs)
  if (premiosState.length > 0) {
    body += '-- ALLWAYS_PREMIOS sorteo state (UPDATE statements)\n';
    for (const p of premiosState) {
      const cup = p.CUPON_GANADOR_ID === null ? 'NULL' : String(p.CUPON_GANADOR_ID);
      const fec = p.FECHA_SORTEO === null
        ? 'NULL'
        : quoteSqlValue(p.FECHA_SORTEO);
      body += `UPDATE ALLWAYS_PREMIOS SET CUPON_GANADOR_ID = ${cup}, FECHA_SORTEO = ${fec} WHERE ID = ${p.ID};\n`;
    }
    body += '\n';
  }

  body += 'COMMIT;\n';

  fs.writeFileSync(SQL_FILE, header + body);

  const stat = fs.statSync(SQL_FILE);
  console.log(`[BACKUP] SQL escrito: ${SQL_FILE} (${stat.size} bytes)`);
  console.log(`[BACKUP] Contagens escritas: ${COUNTS_FILE}`);
  console.log('[BACKUP] OK');
})().catch((e) => {
  console.error('[BACKUP] ERROR:', e.message);
  console.error(e);
  process.exit(1);
});
